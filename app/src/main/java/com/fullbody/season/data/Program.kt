    fun dayById(id: String): DayPlan = days.first { it.id == id }

    /** Число подходов упражнения с учётом недели цикла: 1 — калибровка, 8 — разгрузка. */
    fun setsForWeek(baseSets: Int, cycleWeek: Int): Int = when {
        cycleWeek == 1 && baseSets == 4 -> 3
        cycleWeek == 8 -> (baseSets + 1) / 2
        else -> baseSets
    }
